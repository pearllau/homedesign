import { chromium, expect } from '@playwright/test';
import { recognizedGeometry } from '../e2e/fixtures/recognized-plan.ts';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/floorplan/recognize',r=>r.fulfill({json:{geometry:recognizedGeometry}}));
 await page.goto('http://localhost:3000/');
 await page.getByRole('button',{name:'上传户型图',exact:true}).click();
 assert.equal(await page.locator('.floorplan-import-sidebar').isVisible(),false);
 const png=await page.locator('.floorplan-canvas-wrap').screenshot();
 await page.locator('input[type=file]').first().setInputFiles({name:'floorplan.png',mimeType:'image/png',buffer:png});
 await page.waitForURL('**/design');
 await page.locator('iframe').waitFor();
 const frame=page.frameLocator('iframe');
 await frame.locator('#gRooms polygon').first().waitFor();
 assert.ok(await frame.locator('#stage').evaluate(el=>el.getBoundingClientRect().height>400),'canvas has usable height');
 await frame.locator('#viewSeg [data-view="3d"]').click();
 await frame.locator('body.m3d').waitFor();
 await frame.locator('#view3d canvas').waitFor();
 await frame.locator('#viewSeg [data-view="2d"]').click();
 await frame.locator('body:not(.m3d):not(.busy)').waitFor();
 assert.equal(await page.getByRole('dialog').count(),0);
 await frame.locator('#tgLib').click();
 await frame.locator('.lib .item').first().waitFor();
 await expect.poll(()=>frame.locator('aside.lib').evaluate(el=>el.getBoundingClientRect().width)).toBeGreaterThan(200);
 await frame.locator('.lib .item').first().click();
 await frame.locator('#gFurn > *').first().waitFor();
 await page.screenshot({path:'.tmp/workspace-fixed.png'});
 await frame.locator('.rail-tools summary').click();
 await frame.locator('[data-layer=grid]').click();
 await frame.locator('.rail-tools summary').click();
 await page.getByLabel('语言',{exact:true}).selectOption('en');
 await frame.getByRole('button',{name:'2D Plan',exact:true}).waitFor();
 await page.getByLabel('语言',{exact:true}).selectOption('zh');
 await page.reload();
 await page.waitForURL('**/');
 assert.equal(await page.locator('.home-upload-entry').count(),1,'reload starts a fresh chat');
 assert.equal(await page.locator('iframe').count(),0,'previous floorplan is not restored');
 await page.getByRole('button',{name:'上传户型图',exact:true}).click();
 assert.equal(await page.locator('.floorplan-upload-grid').count(),1,'upload entry opens');
 await page.getByRole('button',{name:'关闭户型图导入'}).click();
 await page.goto('http://localhost:3000/');
 await page.getByRole('button',{name:'上传户型图',exact:true}).click();
 const nextPng=await page.locator('.floorplan-canvas-wrap').screenshot();
 await page.locator('input[type=file]').first().setInputFiles({name:'floorplan-again.png',mimeType:'image/png',buffer:nextPng});
 await page.waitForURL('**/design');
 const freshFrame=page.frameLocator('iframe');
 await freshFrame.locator('#gRooms polygon').first().waitFor();
 await page.getByRole('button',{name:'校准校对',exact:true}).click();
 await page.getByRole('heading',{name:'校准并校对户型'}).waitFor();
 await page.getByRole('button',{name:'关闭户型图导入'}).click();
 assert.deepEqual(errors,[]);
 console.log('PASS: upload auto-recognition → /design; original geometry rendered; drawers; grid; language; reload; calibration reentry; no page errors');
} finally {await browser.close();}
